#!/usr/bin/env python3
# Same job as build-security.cjs + build-secure-engine.cjs, for a Mac without Node:
# refresh the CSP hashes in index.html / cards.html, then generate supabase/functions/_shared/engine.mjs.
# Run after changing any browser code:  python3 tools/build-security.py
import base64, hashlib, os, re, sys

root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
def b64(alg, data): return base64.b64encode(hashlib.new(alg, data).digest()).decode()
def read(p): return open(os.path.join(root, p), encoding='utf-8').read()
def write(p, s):
    with open(os.path.join(root, p), 'w', encoding='utf-8', newline='') as f: f.write(s)

vendor = open(os.path.join(root, 'vendor/supabase-2.45.4.min.js'), 'rb').read()
SCRIPT = re.compile(r'<script[^>]*>([\s\S]*?)</script>')
for name in ['index.html', 'cards.html']:
    html = read(name)
    html = re.sub(r'<meta name="security-build"[^>]*>\s*', '', html)
    html = re.sub(r'<meta http-equiv="Content-Security-Policy"[^>]*>\s*', '', html)
    html = re.sub(r'<meta name="referrer" content="no-referrer">\s*', '', html)
    if name == 'index.html':
        html = html.replace("sc.src = 'https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.45.4/dist/umd/supabase.min.js';", "sc.src = 'vendor/supabase-2.45.4.min.js';")
        html = re.sub(r"sc\.integrity = '[^']*';\s*", '', html)
        html = html.replace("sc.src = 'vendor/supabase-2.45.4.min.js';", "sc.src = 'vendor/supabase-2.45.4.min.js'; sc.integrity = 'sha384-" + b64('sha384', vendor) + "';")
    hashes = ["'sha256-" + b64('sha256', m.group(1).encode('utf-8')) + "'" for m in SCRIPT.finditer(html) if m.group(1).strip()]
    policy = '; '.join(["default-src 'self'", "script-src 'self' " + ' '.join(hashes), "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
                        "font-src 'self' https://fonts.gstatic.com data:", "img-src 'self' data: blob: https://laolegendwars.com https://xahuvoounkdojfsvnfaj.supabase.co", "media-src 'self' blob:",
                        "connect-src 'self' https://xahuvoounkdojfsvnfaj.supabase.co wss://xahuvoounkdojfsvnfaj.supabase.co", "worker-src 'self'", "object-src 'none'", "base-uri 'none'", "form-action 'self'"])
    meta = '<meta name="security-build" content="1">\n<meta http-equiv="Content-Security-Policy" content="' + policy + '">\n<meta name="referrer" content="no-referrer">\n'
    m = re.match(r'(?i)<!doctype[^>]*>', html)
    html = html[:m.end()] + '\n' + meta + html[m.end():] if m else meta + html
    write(name, html)

# the server engine: the shipped rules wrapped for the server (and for the browser's local bot games)
html = read('index.html')
src = sorted([m.group(1) for m in SCRIPT.finditer(html)], key=len)[-1]
tail = re.compile(r'choiceRestore\(\);\s*render\(\);\s*acctStart\(\);\s*liveCheck\(\);\s*\}\)\(\);\s*$')
if not tail.search(src): sys.exit('Engine startup changed: update extraction')
src = src.replace("  startTurn();\n}\nfunction gameOver", "  await startTurn();\n}\nfunction gameOver", 1)
src = src.replace('if(!S.fast){ render(); await fxFuseEmerge(c, M); }', '{ render(); await fxFuseEmerge(c, M); }', 1)
runtime = read('supabase/functions/_shared/engine-runtime.inc')
src = src.replace('(function(){', 'return (function(){', 1)
src = tail.sub(lambda m: runtime + '\nreturn serverAPI;\n})();', src, count=1)
prefix = ("// GENERATED by tools/build-secure-engine.cjs. Do not hand edit.\nimport {diffVisual} from './visual.mjs';\nexport const RULES_HASH='" + hashlib.sha256(src.encode('utf-8')).hexdigest() + "';\nexport function createEngine(){\n"
          "const dummy=new Proxy(function(){},{get(_,k){if(k==='then')return undefined;if(k==='querySelectorAll')return()=>[];if(k==='matches')return false;return dummy;},apply(){return dummy},set(){return true}});\n"
          "const window={addEventListener(){}},document=dummy,navigator={},localStorage={getItem:()=>null,setItem(){},removeItem(){}},location={hostname:'server',protocol:'server:',search:'',hash:''};\n"
          "const matchMedia=()=>({matches:true}),Image=function(){},HTMLImageElement=function(){},innerWidth=1280,innerHeight=720,requestAnimationFrame=()=>0,setInterval=()=>0,clearInterval=()=>{},setTimeout=()=>0,clearTimeout=()=>{},confirm=()=>false;\n"
          "// Cosmetic randomness must never consume gameplay randomness or differ during decision replay.\nconst Math=Object.create(globalThis.Math);Math.random=()=>.5;\n")
write('supabase/functions/_shared/engine.mjs', prefix + src + '\n}\n')

# the dashboard copy (same as tools/build-edge-bundle.cjs): one file the owner pastes into Supabase → Edge Functions →
# secure-game → Code → index.ts → Deploy updates, when the Supabase CLI is not installed. No credentials in it.
parts = []
for p in ['_shared/visual.mjs', '_shared/engine.mjs', '_shared/security.mjs', 'secure-game/index.ts']:
    t = '\n'.join(l for l in read('supabase/functions/' + p).split('\n') if not l.startswith('import '))
    parts.append(re.sub(r'(?m)^export ', '', t))
write('supabase/secure-game-deploy.txt', '\n'.join(parts))
print('CSP refreshed, engine generated, dashboard copy supabase/secure-game-deploy.txt written')
